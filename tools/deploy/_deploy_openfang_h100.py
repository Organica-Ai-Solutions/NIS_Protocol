#!/usr/bin/env python3
"""
Deploy OpenFang Agent OS to H100
=================================
1. Installs OpenFang via official installer (~/.openfang/bin/openfang)
2. Writes ~/.openfang/config.toml (vLLM + NIS MCP)
3. Creates ~/.openfang/agents/nis-picker/agent.toml
4. Sets OPENAI_API_KEY=nis-local in ~/.openfang/.env
5. Starts OpenFang on port 4200
6. Verifies http://localhost:4200/api/health

Usage: python _deploy_openfang_h100.py
"""
import json, subprocess, sys, time, urllib.request

SSH = ["ssh", "-o", "StrictHostKeyChecking=no", "-o", "UserKnownHostsFile=/dev/null",
       "awesome-gpu-name"]

sys.stdout.reconfigure(encoding="utf-8", errors="replace")


def run(cmd_str: str, timeout: int = 60) -> tuple[str, int]:
    """Run command on H100 via SSH."""
    result = subprocess.run(SSH + [cmd_str], capture_output=True, text=True, timeout=timeout)
    out = (result.stdout + result.stderr).strip()
    return out, result.returncode


